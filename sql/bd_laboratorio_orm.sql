-- 1. Esquema
CREATE SCHEMA inventario;

-- 2. Crear tabla tipo_equipo
CREATE TABLE inventario.tipo_equipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(250),

    CONSTRAINT pk_tipo_equipo
        PRIMARY KEY (id_tipo),

    CONSTRAINT uq_tipo_equipo_nombre
        UNIQUE (nombre),

    CONSTRAINT chk_tipo_equipo_nombre
        CHECK (BTRIM(nombre) <> '')
);

-- 3. Crear tabla equipo
CREATE TABLE inventario.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL DEFAULT 0,
    id_tipo BIGINT NOT NULL,

    CONSTRAINT pk_equipo
        PRIMARY KEY (id_equipo),

    CONSTRAINT uq_equipo_codigo
        UNIQUE (codigo),

    CONSTRAINT chk_equipo_codigo
        CHECK (BTRIM(codigo) <> ''),

    CONSTRAINT chk_equipo_nombre
        CHECK (BTRIM(nombre) <> ''),

    CONSTRAINT chk_equipo_cantidad
        CHECK (cantidad >= 0),

    CONSTRAINT chk_equipo_estado
        CHECK (
            estado IN (
                'Disponible',
                'En mantenimiento',
                'Fuera de servicio'
            )
        ),

    CONSTRAINT fk_equipo_tipo
        FOREIGN KEY (id_tipo)
        REFERENCES inventario.tipo_equipo (id_tipo)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

